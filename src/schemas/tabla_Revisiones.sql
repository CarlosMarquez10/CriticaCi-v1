-- Tabla para almacenar las revisiones de clientes y sus Revisiones asociadas

CREATE TABLE clientes_servicios (
    id INT AUTO_INCREMENT PRIMARY KEY,
    CLIENTE_ID VARCHAR(20) NOT NULL,
    NOMBRE VARCHAR(150),
    DIRECCION VARCHAR(150),
    MUNICIPIO VARCHAR(80),
    CICLO VARCHAR(30),
    CLASE_SERVICIO VARCHAR(80),
    TARIFA VARCHAR(30),
    ESTRATO VARCHAR(10),
    ESTADO_SUMINISTRO VARCHAR(80),
    RUTA_LECTURA VARCHAR(30),
    
    SERIE_R VARCHAR(30), MARCA_R VARCHAR(30), FACTOR_MUL_R VARCHAR(10),
    UBICACION_R VARCHAR(50), PROPIEDAD_R VARCHAR(30), ACCION_MEDIDOR_R VARCHAR(30),
    LECTURA_R VARCHAR(30), OBS_CONSUMO_R TEXT, CAUSA_NO_LECTURA_R TEXT,
    
    SERIE_I VARCHAR(30), MARCA_I VARCHAR(30), FACTOR_MUL_I VARCHAR(10),
    UBICACION_I VARCHAR(50), PROPIEDAD_I VARCHAR(30), ACCION_MEDIDOR_I VARCHAR(30),
    LECTURA_I VARCHAR(30), OBS_CONSUMO_I TEXT, CAUSA_NO_LECTURA_I TEXT,
    
    SERIE_T VARCHAR(30), MARCA_T VARCHAR(30), FACTOR_MUL_T VARCHAR(10),
    UBICACION_T VARCHAR(50), PROPIEDAD_T VARCHAR(30), ACCION_MEDIDOR_T VARCHAR(30),
    LECTURA_T VARCHAR(30), OBS_CONSUMO_T TEXT, CAUSA_NO_LECTURA_T TEXT,
    
    SERIE_X VARCHAR(30), MARCA_X VARCHAR(30), FACTOR_MUL_X VARCHAR(10),
    UBICACION_X VARCHAR(50), PROPIEDAD_X VARCHAR(30), ACCION_MEDIDOR_X VARCHAR(30),
    LECTURA_X VARCHAR(30), OBS_CONSUMO_X TEXT, CAUSA_NO_LECTURA_X TEXT,
    
    NUMERO_REVISION VARCHAR(30), ESTADO_REVISION VARCHAR(30), TIPO_PROCESO VARCHAR(30),
    NUMERO_PROCESO VARCHAR(30), ESTADO_PROCESO VARCHAR(30), NUEVA VARCHAR(10),
    TIPO VARCHAR(30), D_TIPO TEXT, GRUPO_REV VARCHAR(30),
    MOTIVO TEXT, D_MOTIVO TEXT,
    
    FECHA_SOLICITUD VARCHAR(30), FECHA_REVISION VARCHAR(30), FECHA_SISTEMA VARCHAR(30),
    REVISOR VARCHAR(30), D_REVISOR TEXT, GENERADO_POR VARCHAR(30), USER_SISTEMA VARCHAR(30),
    
    IDESTADO VARCHAR(10), TERMINALDESCARGA VARCHAR(30), FECHAULTLABOR VARCHAR(30),
    CORRERIA VARCHAR(30), FECHAINICIOLABOR VARCHAR(30), FECHAFINJORNADA VARCHAR(30),
    OBSERVACION TEXT, D_OBSERVACION TEXT, OBSREVISION TEXT,
    
    INDEX idx_cliente_id (CLIENTE_ID),
    UNIQUE INDEX idx_numero_revision (NUMERO_REVISION)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci ROW_FORMAT=DYNAMIC;



